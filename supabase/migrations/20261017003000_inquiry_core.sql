-- Eigenständiger, zahlungs- und terminunabhängiger Anfragekern.
-- Additiv; zuerst in Staging ausführen. Diese Migration startet keine Buchung,
-- reserviert keine Slots und kommuniziert nicht mit Stripe.

begin;

do $$
begin
  if to_regclass('public.inquiries') is not null
     and obj_description(to_regclass('public.inquiries'), 'pg_class') is distinct from
       'VeriFit managed inquiries v1: eigenständige unverbindliche Traineranfragen.' then
    raise exception 'Inquiry-Migration abgebrochen: public.inquiries existiert mit unbekannter Herkunft.';
  end if;

  if to_regclass('public.inquiry_status_events') is not null
     and obj_description(to_regclass('public.inquiry_status_events'), 'pg_class') is distinct from
       'VeriFit managed inquiry status history v1.' then
    raise exception 'Inquiry-Migration abgebrochen: public.inquiry_status_events existiert mit unbekannter Herkunft.';
  end if;
end $$;

create table if not exists public.inquiries (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients(id) on delete cascade,
  trainer_id uuid not null references public.trainers(id) on delete cascade,
  offer_id uuid references public.trainer_offers(id) on delete set null,
  client_name text not null,
  client_email text not null,
  trainer_name text not null,
  offer_title text,
  message text not null,
  status text not null default 'new',
  idempotency_key uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  status_changed_at timestamptz not null default now(),
  constraint inquiries_message_length check (char_length(message) between 10 and 1000),
  constraint inquiries_status_valid check (status in ('new', 'viewed', 'contacted', 'declined', 'closed')),
  constraint inquiries_client_idempotency_unique unique (client_id, idempotency_key)
);

comment on table public.inquiries is
  'VeriFit managed inquiries v1: eigenständige unverbindliche Traineranfragen.';
comment on column public.inquiries.idempotency_key is
  'Vom Client erzeugte UUID; innerhalb eines Kundenkontos dauerhaft eindeutig. Identische Wiederholungen liefern dieselbe Anfrage.';
comment on column public.inquiries.client_email is
  'Kontaktadresse zum Anfragezeitpunkt; nur Kunde, zuständiger Trainer und Admin dürfen den Datensatz lesen.';

create index if not exists inquiries_client_created_idx
  on public.inquiries (client_id, created_at desc);
create index if not exists inquiries_trainer_created_idx
  on public.inquiries (trainer_id, created_at desc);
create index if not exists inquiries_client_rate_idx
  on public.inquiries (client_id, created_at);

create table if not exists public.inquiry_status_events (
  id bigint generated by default as identity primary key,
  inquiry_id uuid not null references public.inquiries(id) on delete cascade,
  from_status text,
  to_status text not null,
  changed_by uuid not null,
  actor_role text not null,
  changed_at timestamptz not null default now(),
  constraint inquiry_status_events_from_valid check (
    from_status is null or from_status in ('new', 'viewed', 'contacted', 'declined', 'closed')
  ),
  constraint inquiry_status_events_to_valid check (
    to_status in ('new', 'viewed', 'contacted', 'declined', 'closed')
  ),
  constraint inquiry_status_events_actor_role_valid check (actor_role in ('client', 'trainer', 'admin'))
);

comment on table public.inquiry_status_events is
  'VeriFit managed inquiry status history v1.';

create index if not exists inquiry_status_events_inquiry_idx
  on public.inquiry_status_events (inquiry_id, changed_at asc);

alter table public.inquiries enable row level security;
alter table public.inquiries force row level security;
alter table public.inquiry_status_events enable row level security;
alter table public.inquiry_status_events force row level security;

drop policy if exists inquiries_participant_select on public.inquiries;
create policy inquiries_participant_select
on public.inquiries
for select
to authenticated
using (
  auth.uid() = client_id
  or auth.uid() = trainer_id
  or public.is_admin()
);

drop policy if exists inquiry_status_events_participant_select on public.inquiry_status_events;
create policy inquiry_status_events_participant_select
on public.inquiry_status_events
for select
to authenticated
using (
  exists (
    select 1
    from public.inquiries inquiry
    where inquiry.id = inquiry_status_events.inquiry_id
      and (
        inquiry.client_id = auth.uid()
        or inquiry.trainer_id = auth.uid()
        or public.is_admin()
      )
  )
);

revoke all privileges on table public.inquiries from public, anon, authenticated;
revoke all privileges on table public.inquiry_status_events from public, anon, authenticated;
grant select on table public.inquiries to authenticated;
grant select on table public.inquiry_status_events to authenticated;

create or replace function public.create_inquiry(
  p_trainer_id uuid,
  p_offer_id uuid,
  p_message text,
  p_idempotency_key uuid
)
returns table (inquiry_id uuid, was_created boolean)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_role text;
  v_client_name text;
  v_client_email text;
  v_trainer_name text;
  v_offer_title text;
  v_message text := btrim(p_message);
  v_existing public.inquiries%rowtype;
  v_inquiry_id uuid;
begin
  if v_user_id is null then
    raise exception using errcode = '42501', message = 'INQUIRY_UNAUTHENTICATED';
  end if;

  select profile.role
    into v_role
  from public.profiles profile
  where profile.id = v_user_id;

  if v_role is distinct from 'client' then
    raise exception using errcode = '42501', message = 'INQUIRY_CLIENT_ONLY';
  end if;

  if p_trainer_id is null or p_idempotency_key is null
     or char_length(v_message) < 10 or char_length(v_message) > 1000 then
    raise exception using errcode = '22023', message = 'INQUIRY_INVALID_INPUT';
  end if;

  select coalesce(nullif(btrim(client.name), ''), client.email), client.email
    into v_client_name, v_client_email
  from public.clients client
  where client.id = v_user_id;

  if not found then
    raise exception using errcode = '42501', message = 'INQUIRY_CLIENT_MISSING';
  end if;

  select coalesce(nullif(btrim(trainer.name), ''), 'Trainer')
    into v_trainer_name
  from public.trainers trainer
  where trainer.id = p_trainer_id
    and trainer.status = 'approved';

  if not found then
    raise exception using errcode = 'P0002', message = 'INQUIRY_TRAINER_UNAVAILABLE';
  end if;

  if p_offer_id is not null then
    select offer.title
      into v_offer_title
    from public.trainer_offers offer
    where offer.id = p_offer_id
      and offer.trainer_id = p_trainer_id
      and offer.is_active is true
      and (
        (offer.type = 'discovery' and coalesce(offer.price, 0) = 0)
        or (offer.type = 'paid' and offer.price > 0)
      );

    if not found then
      raise exception using errcode = '22023', message = 'INQUIRY_OFFER_UNAVAILABLE';
    end if;
  end if;

  -- Serialisiert neue Anfragen je Kunde. Dadurch können parallele Requests weder
  -- Idempotenz noch das datenbankweite Nutzerlimit umgehen.
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('verifit-inquiry:' || v_user_id::text, 0)
  );

  select inquiry.*
    into v_existing
  from public.inquiries inquiry
  where inquiry.client_id = v_user_id
    and inquiry.idempotency_key = p_idempotency_key;

  if found then
    if v_existing.trainer_id = p_trainer_id
       and v_existing.offer_id is not distinct from p_offer_id
       and v_existing.message = v_message then
      return query select v_existing.id, false;
      return;
    end if;

    raise exception using errcode = '22023', message = 'INQUIRY_IDEMPOTENCY_CONFLICT';
  end if;

  if (
    select count(*)
    from public.inquiries inquiry
    where inquiry.client_id = v_user_id
      and inquiry.created_at > now() - interval '1 hour'
  ) >= 5
  or (
    select count(*)
    from public.inquiries inquiry
    where inquiry.client_id = v_user_id
      and inquiry.created_at > now() - interval '24 hours'
  ) >= 20 then
    raise exception using errcode = 'P0001', message = 'INQUIRY_RATE_LIMIT';
  end if;

  insert into public.inquiries (
    client_id,
    trainer_id,
    offer_id,
    client_name,
    client_email,
    trainer_name,
    offer_title,
    message,
    idempotency_key
  ) values (
    v_user_id,
    p_trainer_id,
    p_offer_id,
    v_client_name,
    v_client_email,
    v_trainer_name,
    v_offer_title,
    v_message,
    p_idempotency_key
  )
  returning id into v_inquiry_id;

  insert into public.inquiry_status_events (
    inquiry_id,
    from_status,
    to_status,
    changed_by,
    actor_role
  ) values (
    v_inquiry_id,
    null,
    'new',
    v_user_id,
    'client'
  );

  return query select v_inquiry_id, true;
end;
$$;

create or replace function public.transition_inquiry_status(
  p_inquiry_id uuid,
  p_status text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_role text;
  v_inquiry public.inquiries%rowtype;
begin
  if v_user_id is null then
    raise exception using errcode = '42501', message = 'INQUIRY_UNAUTHENTICATED';
  end if;

  select profile.role
    into v_role
  from public.profiles profile
  where profile.id = v_user_id;

  if v_role is distinct from 'trainer' then
    raise exception using errcode = '42501', message = 'INQUIRY_TRAINER_ONLY';
  end if;

  if p_status is null or p_status not in ('new', 'viewed', 'contacted', 'declined', 'closed') then
    raise exception using errcode = '22023', message = 'INQUIRY_INVALID_STATUS';
  end if;

  select inquiry.*
    into v_inquiry
  from public.inquiries inquiry
  where inquiry.id = p_inquiry_id
  for update;

  if not found or v_inquiry.trainer_id is distinct from v_user_id then
    raise exception using errcode = 'P0002', message = 'INQUIRY_NOT_FOUND';
  end if;

  if v_inquiry.status = p_status then
    return v_inquiry.status;
  end if;

  if not (
    (v_inquiry.status = 'new' and p_status in ('viewed', 'declined', 'closed'))
    or (v_inquiry.status = 'viewed' and p_status in ('contacted', 'declined', 'closed'))
    or (v_inquiry.status = 'contacted' and p_status = 'closed')
    or (v_inquiry.status = 'declined' and p_status = 'closed')
  ) then
    raise exception using errcode = '22023', message = 'INQUIRY_INVALID_TRANSITION';
  end if;

  update public.inquiries
  set status = p_status,
      status_changed_at = now(),
      updated_at = now()
  where id = v_inquiry.id;

  insert into public.inquiry_status_events (
    inquiry_id,
    from_status,
    to_status,
    changed_by,
    actor_role
  ) values (
    v_inquiry.id,
    v_inquiry.status,
    p_status,
    v_user_id,
    'trainer'
  );

  return p_status;
end;
$$;

alter function public.create_inquiry(uuid, uuid, text, uuid) owner to postgres;
alter function public.transition_inquiry_status(uuid, text) owner to postgres;

revoke all on function public.create_inquiry(uuid, uuid, text, uuid) from public, anon, authenticated;
revoke all on function public.transition_inquiry_status(uuid, text) from public, anon, authenticated;
grant execute on function public.create_inquiry(uuid, uuid, text, uuid) to authenticated;
grant execute on function public.transition_inquiry_status(uuid, text) to authenticated;

commit;
